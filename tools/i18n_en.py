def main() -> None:
    rows = list(csv.reader(io.StringIO(CSV.read_text(encoding="utf-8"))))
    header = rows[0]
    de = header.index("de")
    en = header.index("en") if "en" in header else -1
    out = io.StringIO()
    writer = csv.writer(out, lineterminator="\n")
    writer.writerow(["keys", "de", "en"])
    missing = []
    for row in rows[1:]:
        if not row or not row[0]:
            continue
        english = EN.get(row[0], row[en] if 0 <= en < len(row) else "")
        if not english:
            missing.append(row[0])
        writer.writerow([row[0], row[de], english])
    CSV.write_text(out.getvalue(), encoding="utf-8", newline="")
    if missing:
        sys.exit("no English for: " + ", ".join(missing))
    print(f"{len(rows) - 1} keys, all with English")


if __name__ == "__main__":
    main()
